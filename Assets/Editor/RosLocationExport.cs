using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;
using UnityEngine.SceneManagement;

// Tools > Export ROS Locations: writes every pallet and workbench of the open scene to a YAML in the
// ROS map frame. Same origin as PlanarOdometryPublisher (robotBase pose at Play), so the map/odom
// built from this spawn and the exported coordinates agree.
public static class RosLocationExport
{
    struct Entry { public string path; public float x, y, yaw, height; }

    [MenuItem("Tools/Export ROS Locations")]
    static void Export()
    {
        // In Play mode robotBase has driven away from the spawn, so every coordinate would be off
        if (EditorApplication.isPlayingOrWillChangePlaymode)
        {
            Debug.LogError("[ROS Export] Stop Play first: the export needs the robot at its spawn pose.");
            return;
        }
        var scene = SceneManager.GetActiveScene();
        var odom = Object.FindObjectOfType<PlanarOdometryPublisher>();
        if (odom == null || odom.robotBase == null)
        {
            Debug.LogError("[ROS Export] No PlanarOdometryPublisher with robotBase in the open scene.");
            return;
        }
        Vector3 origin = odom.robotBase.position;
        Quaternion inv = Quaternion.Inverse(Quaternion.Euler(0f, odom.robotBase.eulerAngles.y, 0f));

        var all = scene.GetRootGameObjects().SelectMany(g => g.GetComponentsInChildren<Transform>(true)).ToList();
        var packages = new List<Entry>();
        var stations = new List<Entry>();
        Transform robot = odom.robotBase.root;
        foreach (var t in all)
        {
            if (t.IsChildOf(robot)) continue;  // the pallet carried on the forks is not a location
            // Pallet centre = TopDeck centre (the prefab pivot sits on a corner); forks enter along its local Z
            if (t.name == "TopDeck" && t.parent != null && t.parent.name.StartsWith("StandardPallet"))
                packages.Add(Make(t.parent, t.position, new[] { t.forward, -t.forward }, origin, inv));
            else if (t.name.StartsWith("Workbench"))
                stations.Add(Make(t, t.position, new[] { t.right, -t.right, t.forward, -t.forward }, origin, inv));
        }

        string dir = Path.GetFullPath(Path.Combine(Application.dataPath,
            "../../CollaborativeAMRStockerization/catkin_ws/src/amr_navigation/config"));
        string file = EditorUtility.SaveFilePanel("Export ROS Locations", Directory.Exists(dir) ? dir : "",
            "locations_" + scene.name.ToLowerInvariant() + ".yaml", "yaml");
        if (string.IsNullOrEmpty(file)) return;

        var sb = new StringBuilder();
        sb.AppendLine("# Generated by Unity Tools > Export ROS Locations from scene " + scene.name + ". Re-export, do not hand-edit.");
        sb.AppendLine("# Map frame (origin = robot spawn). x, y: object centre (m). yaw: dock heading (deg), the robot");
        sb.AppendLine("# heading while reversing in (points from the object out to the aisle). height: base height (m).");
        Write(sb, "packages", "package", packages);
        Write(sb, "stations", "station", stations);
        File.WriteAllText(file, sb.ToString());
        Debug.LogFormat("[ROS Export] {0} packages, {1} stations -> {2}", packages.Count, stations.Count, file);
    }

    static Entry Make(Transform obj, Vector3 centre, Vector3[] axes, Vector3 origin, Quaternion inv)
    {
        // ponytail: the open side is the axis pointing most toward the spawn, true while racks and benches
        // face the central aisle; add an explicit marker per object if a layout breaks that
        Vector3 toSpawn = origin - centre;
        Vector3 dock = axes.OrderByDescending(a => Vector3.Dot(a, toSpawn)).First();
        Vector3 r = inv * (centre - origin);
        Vector3 d = inv * dock;
        float yaw = Mathf.Atan2(-d.x, d.z) * Mathf.Rad2Deg;  // ROS (x, y) = (Unity z, -Unity x)
        return new Entry { path = PathOf(obj), x = r.z, y = -r.x, yaw = (yaw + 360f) % 360f, height = obj.position.y };
    }

    static void Write(StringBuilder sb, string section, string prefix, List<Entry> items)
    {
        sb.AppendLine(section + ":");
        int i = 1;
        // Rows north to south, then west to east
        foreach (var e in items.OrderByDescending(e => Mathf.Round(e.y * 10f)).ThenBy(e => e.x))
            sb.AppendLine(string.Format(CultureInfo.InvariantCulture,
                "  {0}_{1}: {{x: {2:F3}, y: {3:F3}, yaw: {4:F1}, height: {5:F3}, unity: \"{6}\"}}",
                prefix, i++, e.x, e.y, e.yaw, e.height, e.path));
    }

    static string PathOf(Transform t)
    {
        string p = t.name;
        for (var a = t.parent; a != null; a = a.parent) p = a.name + "/" + p;
        return p;
    }
}
